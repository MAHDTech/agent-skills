import fs from "fs"
import path from "path"
import {execFileSync} from "child_process"
import {log} from "@clack/prompts"

export const ROOT =
    process.env.AGENT_SKILLS_HOME || path.resolve(import.meta.dir, "..", "..")

export function run(
    cmd: string,
    args: string[],
    extraEnv: Record<string, string> = {}
) {
    execFileSync(cmd, args, {
        cwd: ROOT,
        stdio: "inherit",
        env: {...process.env, ...extraEnv},
    })
}

/** Compile the Tailwind CSS bundle. */
export function buildCss() {
    log.step("🎨 Building CSS…")
    run("tailwindcss", [
        "-i",
        "dashboard/css/input.css",
        "-o",
        "dashboard/static/build/css/generated.css",
    ])
}

/**
 * Compute each skill's last-modified date from git history and write a Zola data
 * sidecar (`dashboard/skill_dates.toml`, git-ignored).
 */
export function writeSkillDates() {
    log.step("🕗 Reading last-modified dates from git…")
    const skillsDir = path.join(ROOT, "skills")
    const dates: Record<string, string> = {}
    for (const category of fs.readdirSync(skillsDir)) {
        const catPath = path.join(skillsDir, category)
        if (!fs.statSync(catPath).isDirectory()) continue
        for (const name of fs.readdirSync(catPath)) {
            if (!fs.existsSync(path.join(catPath, name, "SKILL.md"))) continue
            try {
                const out = execFileSync(
                    "git",
                    [
                        "log",
                        "-1",
                        "--date=short",
                        "--format=%cd",
                        "--",
                        `skills/${category}/${name}`,
                    ],
                    {cwd: ROOT, encoding: "utf8"}
                ).trim()
                if (out) dates[`${category}/${name}`] = out
            } catch {
                // No git history
            }
        }
    }
    const body = Object.keys(dates)
        .sort()
        .map((k) => `${JSON.stringify(k)} = ${JSON.stringify(dates[k])}`)
        .join("\n")
    fs.writeFileSync(
        path.join(ROOT, "dashboard", "skill_dates.toml"),
        `# Generated by \`dashboard --action build\` from git — do not commit.\n[dates]\n${body}\n`
    )
}

/** Manually clean output directory with retries to avoid race conditions with watchers / sync services. */
export function cleanOutputDir(
    publicDir: string = path.join(ROOT, "dashboard", "public")
) {
    if (!fs.existsSync(publicDir)) return

    log.step("🧹 Cleaning output directory…")
    const maxRetries = 5
    const delayMs = 150

    for (let attempt = 1; attempt <= maxRetries; attempt++) {
        try {
            fs.rmSync(publicDir, {recursive: true, force: true})
            return
        } catch (err) {
            if (attempt === maxRetries) {
                log.warn(
                    `⚠️ Failed to clean directory ${publicDir}: ${(err as Error).message}. Proceeding anyway…`
                )
                return
            }
            // Sleep/block before retrying using a non-busy-waiting synchronous wait
            Atomics.wait(
                new Int32Array(new SharedArrayBuffer(4)),
                0,
                0,
                delayMs
            )
        }
    }
}

/** Regenerate skill content, build CSS, render the site, index it. */
export function build() {
    log.step("🔄 Syncing generated content…")
    run("bun", ["run", "skills", "--action", "sync"], {SKILLS_REPO_ONLY: "1"})
    buildCss()
    writeSkillDates()
    cleanOutputDir()
    log.step("🏗️  Building Zola site…")
    run("zola", ["--root", "dashboard", "build"])
    log.step("🔍 Indexing with Pagefind…")
    run("pagefind", [
        "--site",
        "dashboard/public",
        "--output-subdir",
        "pagefind",
    ])
}
